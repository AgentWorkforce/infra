#!/usr/bin/env bash
# Prints docs/azure-install/ingress.yaml: the AKS Traefik edge rendered from
# the agent-relay chart (traefikIngress, gate off), with the four host
# placeholders the AKS guide replaces. For releases whose chart predates
# traefikIngress; on newer charts set traefikIngress.enabled instead.
#
#   scripts/selfhost/aks-traefik-ingress.sh > docs/azure-install/ingress.yaml
#
# ci/agent-relay/test_traefik_ingress.py fails when the file and this output differ.
# Blank lines are dropped so Helm 3 and Helm 4 print the same file.
set -euo pipefail
cd "$(dirname "$0")/../.."
cat <<'HEAD'
# GENERATED by scripts/selfhost/aks-traefik-ingress.sh from the agent-relay
# chart (traefikIngress); do not hand-edit. The public edge for Agent Relay on
# AKS: one Traefik Ingress with host rules (the routes of eksIngress and
# gkeIngress) and an edge-deny Service with no endpoints, so denied paths
# (/internal on api, cast and history, Relaycast workspace create, and
# everything unlisted on the history host) get a 503 from Traefik.
# TLS: cert-manager (ClusterIssuer letsencrypt) keeps Secret agent-relay-tls.
# Replace __HOST_ROOT__, __HOST_API__, __HOST_CAST__, __HOST_HISTORY__.
# With agent-relay chart 0.7.77 or later, set traefikIngress.enabled in
# values.yaml instead of applying this file.
HEAD
helm template agent-relay charts/agent-relay -n agent-relay --no-hooks \
  --show-only templates/traefik-ingress.yaml \
  -f charts/agent-relay/values-gcp-proof.yaml -f charts/agent-relay/ci/traefik-ingress-values.yaml \
  --set traefikIngress.hosts.root=root.placeholder.invalid --set traefikIngress.hosts.api=api.placeholder.invalid \
  --set traefikIngress.hosts.cast=cast.placeholder.invalid --set traefikIngress.hosts.history=history.placeholder.invalid |
  grep -v -e '^# Source:' -e 'helm.sh/chart' -e 'app.kubernetes.io/managed-by' -e '^\s*$' |
  sed -e 's/root\.placeholder\.invalid/__HOST_ROOT__/g' -e 's/api\.placeholder\.invalid/__HOST_API__/g' \
      -e 's/cast\.placeholder\.invalid/__HOST_CAST__/g' -e 's/history\.placeholder\.invalid/__HOST_HISTORY__/g'
