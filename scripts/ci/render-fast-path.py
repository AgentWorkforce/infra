#!/usr/bin/env python3
"""Render .github/workflows/fast-path.yml from the release workflows.

The fast path runs infra's release-candidate intake, the release-candidate tag
and the leaf-chart publish (with every Lint Charts job in front of it) on
Blacksmith runners, outside the shared GitHub-hosted queue. Its jobs are not
hand-copied: this script takes them verbatim from

  .github/workflows/release-candidate.yml   (stage: candidate)
  .github/workflows/release-candidate-tag.yml (stage: tag)
  .github/workflows/lint.yml + release.yml  (stage: charts)
  .github/workflows/slack-relay.yml         (stage: slack-relay-image)

and changes only what running from a workflow_dispatch requires: the runner,
the checked-out commit (pinned to the approved SHA), the trigger conditions
and the tag job's pull request number. Every guard in the source steps is
kept byte for byte. The slack-relay image job also swaps its push-on-main
conditions and :main tag for an unconditional push of fast-<sha> and
sha-<short sha>: the fast path never moves :main. ci/agent-relay/test_release_candidate.py fails when the
checked-in workflow differs from a fresh render, so a change to any source
workflow must be followed by:

  python3 scripts/ci/render-fast-path.py

The umbrella chart publish (release-agent-relay.yml) is deliberately NOT part
of the fast path: customer upgrades verify its release assets with
`gh attestation verify --signer-workflow .../release-agent-relay.yml
--source-ref refs/tags/agent-relay-X.Y.Z --deny-self-hosted-runners`
(scripts/selfhost/agent-relay-upgrade.sh), and Blacksmith runners are
self-hosted runners to GitHub, so assets attested here would be refused.
"""

from __future__ import annotations

import argparse
import copy
import difflib
import pathlib
import re
import sys

import yaml


ROOT = pathlib.Path(__file__).resolve().parents[2]
WORKFLOWS = ROOT / ".github/workflows"
OUTPUT = WORKFLOWS / "fast-path.yml"
RUNNER = "blacksmith-4vcpu-ubuntu-2404"
SHA = "${{ needs.gate.outputs.sha }}"
REVIEWER = "Khaliq (khaliqgant)"
# Stages that build an image from `ref` rather than run main's automation.
ANY_REF_STAGES = ["slack-relay-image"]

HEADER = f"""\
# GENERATED by scripts/ci/render-fast-path.py from release-candidate.yml,
# release-candidate-tag.yml, lint.yml, release.yml and slack-relay.yml. Do not
# edit by hand:
# change the source workflow, then run `python3 scripts/ci/render-fast-path.py`.
#
# Fast path: infra's release steps on Blacksmith runners, outside the shared
# GitHub-hosted queue. Anyone with write access (people or agents) may start
# it; nothing runs until {REVIEWER} approves the `fast-path`
# environment on the first job. Every later job needs that job. The stages:
#
#   candidate  release-candidate.yml: verify a published component image
#              (policy, provenance) and pin it on the release/agent-relay-X.Y.Z
#              PR, then request exact-head acceptance (which runs on the
#              self-hosted acceptance runner, not the shared queue).
#   tag        release-candidate-tag.yml for a merged release PR: validate the
#              exact-head gate evidence and push the agent-relay-X.Y.Z tag.
#   charts     every Lint Charts job, then release.yml: chart-releaser and the
#              GHCR OCI push for leaf charts whose version is not yet published.
#   slack-relay-image
#              slack-relay.yml: the slack-relay tests, then build and push
#              ghcr.io/agentworkforce/slack-relay:fast-<sha> and :sha-<short>
#              (never :main) with the same provenance and SBOM. `ref` may be any
#              branch or commit; the digest is in the run summary.
#
# Every guard is the source workflow's own step, unchanged: FROZEN candidates,
# digest/commit validation, blocked digests, attestation and Sigstore checks,
# exact-head acceptance and approvals, the tag-moves-never rule, chart-releaser
# skip_existing and the already-in-GHCR check. For every stage but
# slack-relay-image, `ref` must be the current main head, which is what the
# source workflows check out.
#
# Not here, on purpose: release-agent-relay.yml (the umbrella chart and the
# release assets the agent-relay-X.Y.Z tag triggers). Customer upgrades verify
# those attestations with --deny-self-hosted-runners and the
# release-agent-relay.yml signer, and Blacksmith runners count as self-hosted,
# so that publish stays on GitHub-hosted runners.
"""


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, _str)


def load(name: str) -> dict:
    data = yaml.safe_load((WORKFLOWS / name).read_text(encoding="utf-8"))
    # PyYAML reads the bare `on:` key as boolean True.
    data["on"] = data.pop(True, data.get("on"))
    return data


def pin_checkouts(job: dict, *, replace_ref: set[str]) -> None:
    """Check out the approved SHA wherever the source checked out this repo."""
    for step in job["steps"]:
        if not str(step.get("uses", "")).startswith("actions/checkout@"):
            continue
        settings = step.setdefault("with", {})
        if "repository" in settings:
            continue
        current = settings.get("ref")
        if current is None or current in replace_ref:
            settings["ref"] = SHA
        # Keep the field order readable: ref first.
        step["with"] = {"ref": settings.pop("ref"), **settings}


def fast_job(source: dict, *, stage: str, needs: list[str], env: dict | None = None) -> dict:
    job = copy.deepcopy(source)
    job.pop("if", None)
    job.pop("needs", None)
    job["runs-on"] = RUNNER
    job = {"if": f"inputs.stage == '{stage}'", "needs": needs, **job}
    if env:
        job["env"] = {**env, **job.get("env", {})}
    return job


def substitute(value, old: str, new: str):
    if isinstance(value, str):
        return value.replace(old, new)
    if isinstance(value, list):
        return [substitute(item, old, new) for item in value]
    if isinstance(value, dict):
        return {key: substitute(item, old, new) for key, item in value.items()}
    return value


def check_runs(workflow: dict) -> None:
    """No user-controlled input may be interpolated into a shell script."""
    for name, job in workflow["jobs"].items():
        for step in job.get("steps", []):
            script = step.get("run", "")
            if re.search(r"\$\{\{\s*(github\.event\.)?inputs\.", script):
                raise SystemExit(f"{name}: an input is interpolated into a run script")
            if "github.event.pull_request" in str(step) and name == "tag":
                raise SystemExit("tag: a pull_request event field survived the rewrite")


def find_step(job: dict, *, name: str | None = None, uses: str | None = None) -> dict:
    """The one source step to rewrite; a renamed source step fails the render."""
    found = [
        step
        for step in job["steps"]
        if (name is None or step.get("name") == name)
        and (uses is None or str(step.get("uses", "")).startswith(uses))
    ]
    if len(found) != 1:
        raise SystemExit(f"expected one step name={name!r} uses={uses!r}, found {len(found)}")
    return found[0]


def slack_relay_jobs(src: dict) -> dict:
    stage = "slack-relay-image"
    defaults = copy.deepcopy(src["defaults"])

    test = fast_job(src["jobs"]["test"], stage=stage, needs=["gate"])
    test["defaults"] = copy.deepcopy(defaults)
    pin_checkouts(test, replace_ref=set())
    # No dependency cache: this may build an unreviewed ref, and nothing it
    # produces may be restored by normal CI.
    node = find_step(test, uses="actions/setup-node@")
    node["with"] = {k: v for k, v in node["with"].items() if not k.startswith("cache")}

    image = fast_job(src["jobs"]["image"], stage=stage, needs=["gate", "slack-relay-test"])
    image["defaults"] = copy.deepcopy(defaults)
    pin_checkouts(image, replace_ref=set())
    # The source logs in and pushes only on a push to main; here, always.
    find_step(image, name="Log in to GHCR").pop("if")
    tags = find_step(image, name="Tags")
    tags["env"] = {"SHA": SHA}
    tags["run"] = (
        'image="ghcr.io/${GITHUB_REPOSITORY_OWNER,,}/slack-relay"\n'
        "# Never :main or :latest; deployments pin the digest.\n"
        'echo "image=$image" >> "$GITHUB_OUTPUT"\n'
        'echo "tags=$image:fast-$SHA,$image:sha-${SHA:0:7}" >> "$GITHUB_OUTPUT"\n'
    )
    build = find_step(image, uses="docker/build-push-action@")
    build["name"] = "Build and push"
    build["with"]["push"] = True
    digest = find_step(image, name="Digest")
    digest.pop("if")
    digest["env"] = {
        **digest["env"],
        "IMAGE": "${{ steps.tags.outputs.image }}",
        "TAGS": "${{ steps.tags.outputs.tags }}",
    }
    digest["run"] = (
        "# shellcheck disable=SC2016 # the backticks are literal Markdown\n"
        "{\n"
        '  echo "slack-relay image digest: \\`$DIGEST\\`"\n'
        "  printf -- '- image: `%s@%s`\\n' \"$IMAGE\" \"$DIGEST\"\n"
        "  printf -- '- tags: `%s`\\n' \"$TAGS\"\n"
        '} >> "$GITHUB_STEP_SUMMARY"\n'
    )
    return {"slack-relay-test": test, "slack-relay-image": image}


def render() -> str:
    candidate_src = load("release-candidate.yml")
    tag_src = load("release-candidate-tag.yml")
    lint_src = load("lint.yml")
    release_src = load("release.yml")

    candidate_inputs = candidate_src["on"]["workflow_dispatch"]["inputs"]
    inputs = {
        "ref": {
            "description": "Commit to run from; must be the current main head (slack-relay-image: any branch, tag or commit)",
            "required": True,
            "default": "main",
            "type": "string",
        },
        "reason": {
            "description": "Why this needs the fast path",
            "required": True,
            "type": "string",
        },
        "stage": {
            "description": "candidate (pin an image on the release PR), tag (tag a merged release PR), charts (lint and publish leaf charts) or slack-relay-image (test, build and push slack-relay:fast-<sha>)",
            "required": True,
            "type": "choice",
            "options": ["candidate", "tag", "charts", *ANY_REF_STAGES],
        },
    }
    for key, spec in candidate_inputs.items():
        spec = copy.deepcopy(spec)
        spec["description"] = f"candidate: {spec['description']}"
        if key == "component":
            # A choice input cannot be optional for the other stages. The
            # candidate job's `describe --component` still rejects anything
            # outside update-release-candidate.py's COMPONENTS allowlist.
            spec = {
                "description": spec["description"] + " (" + ", ".join(spec["options"]) + ")",
                "required": False,
                "type": "string",
            }
        else:
            spec["required"] = False
        inputs[key] = spec
    inputs["pr_number"] = {
        "description": "tag: number of the merged release/agent-relay-X.Y.Z pull request",
        "required": False,
        "type": "string",
    }

    gate = {
        "environment": "fast-path",
        "runs-on": RUNNER,
        "timeout-minutes": 10,
        "outputs": {"sha": "${{ steps.sha.outputs.sha }}"},
        "steps": [
            {
                "uses": "actions/checkout@11bd71901bbe5b1630ceea73d27597364c9af683",
                "with": {"ref": "${{ inputs.ref }}", "fetch-depth": 0},
            },
            {
                "name": "Resolve ref and require the current main head",
                "id": "sha",
                "shell": "bash",
                "env": {
                    "REF": "${{ inputs.ref }}",
                    "REASON": "${{ inputs.reason }}",
                    "STAGE": "${{ inputs.stage }}",
                },
                "run": (
                    "set -euo pipefail\n"
                    'sha="$(git rev-parse HEAD)"\n'
                    "git fetch --no-tags origin main\n"
                    'main="$(git rev-parse origin/main)"\n'
                    "# The source workflows run main's automation; so does the fast path.\n"
                    "# An image build may come from any ref: it pushes only fast-/sha- tags.\n"
                    'case "$STAGE" in\n'
                    f'  {"|".join(ANY_REF_STAGES)})\n'
                    '    on_main=no; git merge-base --is-ancestor "$sha" "$main" && on_main=yes ;;\n'
                    "  *)\n"
                    '    if [[ "$sha" != "$main" ]]; then\n'
                    '      echo "::error::ref resolves to $sha; the infra fast path runs only the current main head ($main)."\n'
                    "      exit 1\n"
                    "    fi\n"
                    "    on_main=yes ;;\n"
                    "esac\n"
                    'echo "sha=$sha" >> "$GITHUB_OUTPUT"\n'
                    "# shellcheck disable=SC2016 # the backticks are literal Markdown\n"
                    "{\n"
                    '  echo "### infra fast path: $STAGE"\n'
                    '  printf -- \'- ref: `%s` at `%s`\\n\' "$REF" "$sha"\n'
                    '  printf -- \'- reason: %s\\n\' "$REASON"\n'
                    '  printf -- \'- on main: %s\\n\' "$on_main"\n'
                    '} >> "$GITHUB_STEP_SUMMARY"\n'
                ),
            },
        ],
    }

    jobs: dict = {"gate": gate}

    # stage: candidate. The source's workflow-level permissions move onto the job.
    candidate = fast_job(candidate_src["jobs"]["update"], stage="candidate", needs=["gate"])
    candidate["permissions"] = copy.deepcopy(candidate_src["permissions"])
    pin_checkouts(candidate, replace_ref={"main"})
    jobs["candidate"] = candidate

    # stage: tag. The source runs on a closed pull_request event and filters it
    # with a job `if`; here the same conditions are checked against the API.
    tag = fast_job(tag_src["jobs"]["tag"], stage="tag", needs=["gate"])
    tag = substitute(tag, "github.event.pull_request.number", "inputs.pr_number")
    tag["permissions"] = copy.deepcopy(tag_src["permissions"])
    pin_checkouts(tag, replace_ref={"main"})
    tag["steps"].insert(
        0,
        {
            "name": "Require a merged release pull request (the source's event filter)",
            "shell": "bash",
            "env": {"GH_TOKEN": "${{ github.token }}", "PR_NUMBER": "${{ inputs.pr_number }}"},
            "run": (
                "set -euo pipefail\n"
                '[[ "$PR_NUMBER" =~ ^[1-9][0-9]{0,9}$ ]] \\\n'
                '  || { echo "::error::pr_number must be a pull request number."; exit 1; }\n'
                'pr="$(gh api "repos/$GITHUB_REPOSITORY/pulls/$PR_NUMBER")"\n'
                "jq -e --arg repo \"$GITHUB_REPOSITORY\" '\n"
                '  .merged == true and .base.ref == "main" and\n'
                "  .head.repo.full_name == $repo and\n"
                '  (.head.ref | startswith("release/agent-relay-"))\n'
                "' <<<\"$pr\" >/dev/null \\\n"
                '  || { echo "::error::#$PR_NUMBER is not a merged release/agent-relay-* pull request into main."; exit 1; }\n'
                'gh api --paginate "repos/$GITHUB_REPOSITORY/pulls/$PR_NUMBER/files?per_page=100" \\\n'
                "  --jq '.[].filename' | grep '^releases/' >/dev/null \\\n"
                '  || { echo "::error::#$PR_NUMBER changes nothing under releases/."; exit 1; }\n'
            ),
        },
    )
    tag["concurrency"] = {"group": "fast-path-tag-${{ inputs.pr_number }}", "cancel-in-progress": False}
    jobs["tag"] = tag

    # stage: charts. release.yml publishes only after every lint.yml job passes.
    lint_names = []
    for name, job in lint_src["jobs"].items():
        fast = fast_job(job, stage="charts", needs=["gate"], env=lint_src.get("env"))
        fast.setdefault("permissions", copy.deepcopy(lint_src["permissions"]))
        pin_checkouts(fast, replace_ref=set())
        jobs[f"lint-{name}"] = fast
        lint_names.append(f"lint-{name}")
    charts = fast_job(release_src["jobs"]["release"], stage="charts", needs=["gate", *lint_names])
    pin_checkouts(charts, replace_ref=set())
    charts["steps"].append(
        {
            "name": "Summary",
            "if": "always()",
            "shell": "bash",
            "env": {"CHANGED": "${{ steps.cr.outputs.changed_charts }}"},
            "run": (
                "set -euo pipefail\n"
                "# shellcheck disable=SC2016 # the backticks are literal Markdown\n"
                "{\n"
                '  echo "- chart-releaser changed charts: ${CHANGED:-none}"\n'
                '  echo "- chart versions at this commit (OCI: oci://ghcr.io/agentworkforce/charts/<chart>):"\n'
                "  for chart in charts/*/Chart.yaml; do\n"
                "    printf -- '  - `%s` %s\\n' \"$(basename \"$(dirname \"$chart\")\")\" \\\n"
                "      \"$(sed -n 's/^version: *//p' \"$chart\" | tr -d '\"')\"\n"
                "  done\n"
                '} >> "$GITHUB_STEP_SUMMARY"\n'
            ),
        }
    )
    charts["concurrency"] = {"group": "fast-path-charts", "cancel-in-progress": False}
    jobs["charts"] = charts

    # stage: slack-relay-image. slack-relay.yml's test job unchanged, then its
    # image job pushing fast-<sha> and sha-<short sha> instead of :main.
    jobs.update(slack_relay_jobs(load("slack-relay.yml")))

    workflow = {
        "name": "fast-path",
        "run-name": "fast-path ${{ inputs.ref }} (${{ inputs.reason }})",
        "on": {"workflow_dispatch": {"inputs": inputs}},
        "permissions": {"contents": "read"},
        # No workflow-level concurrency: a run waiting for approval would hold
        # the group, and GitHub keeps one pending run per group, so a third
        # dispatch would silently cancel the second. The tag and charts jobs
        # serialize at job level, which only applies once a run is approved.
        # The candidate intake reconciles its own races (see its source).
        "jobs": jobs,
    }
    check_runs(workflow)
    body = yaml.dump(workflow, Dumper=Dumper, sort_keys=False, width=1000, allow_unicode=True)
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the checked-in file is stale")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(True), rendered.splitlines(True), str(OUTPUT), "rendered"
                )
            )
            print("fast-path.yml is stale: run python3 scripts/ci/render-fast-path.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
